#!/usr/bin/env node
'use strict';

/**
 * Generate the server-side TOOLS USED lookup for the Apps Script web app.
 *
 * Reads the exact audited strips from 01_AUDIT/tools-embeds.json and writes
 * 04_APPS_SCRIPT/ToolsData.gs. The data is served by Code.gs at
 * `?tools=Pxxx` so Behance can embed each strip as a normal iframe.
 *
 * This script does not fetch images or deploy anything.
 *
 * Usage:
 *   node generate-tools.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE_PATH = path.join(ROOT, '01_AUDIT', 'tools-embeds.json');
const OUTPUT_PATH = path.join(ROOT, '04_APPS_SCRIPT', 'ToolsData.gs');
const EXPECTED_TOOLS = 38;

function fail(message) {
  throw new Error(message);
}

function main() {
  const entries = JSON.parse(fs.readFileSync(SOURCE_PATH, 'utf8'));
  if (!Array.isArray(entries) || entries.length !== EXPECTED_TOOLS) {
    fail('Expected ' + EXPECTED_TOOLS + ' TOOLS USED strips');
  }

  const tools = {};
  for (const entry of entries) {
    if (!/^P\d{3}$/.test(entry.project_id || '') ||
        !entry.project_title || !entry.title ||
        !Number.isFinite(entry.width) || !Number.isFinite(entry.height) ||
        !entry.style || !entry.row ||
        !Array.isArray(entry.logos) || !entry.logos.length) {
      fail('Incomplete TOOLS USED entry: ' + (entry.project_id || 'unknown'));
    }
    if (tools[entry.project_id]) {
      fail('Duplicate TOOLS USED entry for ' + entry.project_id);
    }
    tools[entry.project_id] = {
      project_id: entry.project_id,
      project_title: entry.project_title,
      title: entry.title,
      width: entry.width,
      height: entry.height,
      style: entry.style,
      row: entry.row
    };
  }

  const source = [
    '/**',
    ' * Generated by tools/generate-tools.js. Do not edit by hand.',
    ' * Exact audited TOOLS USED strips, one per project.',
    ' * The TOOLS lookup is server-side and is never sent wholesale to a client.',
    ' */',
    'var TOOLS = ' + JSON.stringify(tools, null, 2) + ';',
    ''
  ].join('\n');

  fs.writeFileSync(OUTPUT_PATH, source, 'utf8');
  console.log(JSON.stringify({
    tools: entries.length,
    output: 'migration/04_APPS_SCRIPT/ToolsData.gs'
  }, null, 2));
}

try {
  main();
} catch (error) {
  console.error('ERROR: ' + error.message);
  process.exit(1);
}
